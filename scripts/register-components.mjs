// Regenerates the component sections of src/index.ts and src/styles/index.scss from the
// folders in src/components (every folder with an index.ts is exported; every <Name>.scss imported).
// Usage: node scripts/register-components.mjs [--check]
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const dir = join(root, 'src', 'components');
const names = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort((a, b) => a.localeCompare(b));

const check = process.argv.includes('--check');
let stale = false;

function replaceSection(file, start, end, body) {
  const path = join(root, file);
  const text = readFileSync(path, 'utf8');
  const from = text.indexOf(start);
  const to = end ? text.indexOf(end, from) : text.length;
  if (from === -1 || to === -1) throw new Error(`${file}: markers not found`);
  const next = `${text.slice(0, from)}${start}\n${body}${end ? `\n${text.slice(to)}` : ''}`;
  if (next !== text) {
    stale = true;
    if (!check) writeFileSync(path, next);
  }
}

replaceSection('src/index.ts', '// Components (alphabetical)', null, names.map((n) => `export * from './components/${n}';`).join('\n') + '\n');
const scss = names.filter((n) => existsSync(join(dir, n, `${n}.scss`)));
replaceSection('src/styles/index.scss', '// Components (generated by scripts/register-components.mjs)', null, scss.map((n) => `@import '../components/${n}/${n}';`).join('\n') + '\n');

if (check && stale) {
  console.error('Component registration is stale. Run: node scripts/register-components.mjs');
  process.exit(1);
}
console.log(`${check ? 'Checked' : 'Registered'} ${names.length} components (${scss.length} stylesheets).`);
